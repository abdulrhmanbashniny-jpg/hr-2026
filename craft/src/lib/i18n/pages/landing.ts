/**
 * Strings for the public landing page, the sign-up funnel (/login, /join, /app/onboarding) and the
 * public header and footer. Both languages share one shape; counts go through small plural helpers.
 */

function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  const mod = n % 100;
  if (mod >= 3 && mod <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}

