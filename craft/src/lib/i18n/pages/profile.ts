/** Arabic counted nouns: 1, 2, 3–10 and 11+ take different forms. */
function arCount(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  const r = n % 100;
  return (r >= 3 && r <= 10 ? few : many).replace('{n}', String(n));
}

