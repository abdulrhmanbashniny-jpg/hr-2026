/**
 * Extracts the Kingdom's outline from Natural Earth (public domain, via world-atlas) and writes it
 * as a projected SVG path, so the console map ships with no map library and no tile requests.
 *   node scripts/build-map.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { feature } from 'topojson-client';

const root = path.resolve(import.meta.dirname, '..');
const topo = JSON.parse(await readFile(path.join(root, 'node_modules/world-atlas/countries-50m.json'), 'utf8'));
const sau = feature(topo, topo.objects.countries).features.find((f) => f.id === '682');
if (!sau) throw new Error('Saudi Arabia not found');

// Equirectangular with the x axis scaled by cos(23.9°), the Kingdom's mid-latitude: true enough at this scale.
const LON0 = 34.4, LON1 = 55.8, LAT0 = 16.2, LAT1 = 32.3;
const K = Math.cos((24 * Math.PI) / 180);
const W = 1000;
const H = Math.round((W * (LAT1 - LAT0)) / ((LON1 - LON0) * K));
const px = (lon) => ((lon - LON0) / (LON1 - LON0)) * W;
const py = (lat) => ((LAT1 - lat) / (LAT1 - LAT0)) * H;

const polys = sau.geometry.type === 'Polygon' ? [sau.geometry.coordinates] : sau.geometry.coordinates;
let d = '';
for (const poly of polys) {
  const ring = poly[0];
  if (ring.length < 8) continue;
  let last = null;
  ring.forEach(([lon, lat], i) => {
    const x = px(lon).toFixed(1);
    const y = py(lat).toFixed(1);
    const key = `${x},${y}`;
    if (key === last) return;
    d += `${i === 0 ? 'M' : 'L'}${x} ${y}`;
    last = key;
  });
  d += 'Z';
}

const out = `/** Generated by scripts/build-map.mjs from Natural Earth 1:50m (public domain). Do not edit. */
export const KSA_VIEWBOX = { width: ${W}, height: ${H} } as const;
export const KSA_BOUNDS = { lon0: ${LON0}, lon1: ${LON1}, lat0: ${LAT0}, lat1: ${LAT1} } as const;
export const KSA_PATH = '${d}';

export function project(lon: number, lat: number): { x: number; y: number } {
  return { x: ((lon - KSA_BOUNDS.lon0) / (KSA_BOUNDS.lon1 - KSA_BOUNDS.lon0)) * KSA_VIEWBOX.width, y: ((KSA_BOUNDS.lat1 - lat) / (KSA_BOUNDS.lat1 - KSA_BOUNDS.lat0)) * KSA_VIEWBOX.height };
}
`;
await writeFile(path.join(root, 'src/lib/geo/ksa.ts'), out);
console.log('wrote src/lib/geo/ksa.ts', `${W}x${H}`, `${(d.length / 1024).toFixed(1)} KB`);
